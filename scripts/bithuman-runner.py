def models():
    """id → путь к модели. Папка (несколько лиц) сильнее одиночного файла.

    ⚠️ 18.08. Форматов ДВА. Essence 1 приезжает файлом `.imx`, а семейство Essence 2 —
    `.lebundle` (v2-движок, грузится тем же `AsyncBithuman.create`, но через libengine).
    Раньше здесь стоял только `*.imx`, и купленное лицо на essence-2 раннер просто не
    видел бы — папка пустая, лиц нет, а причина неочевидна.
    """
    out = {}
    d = os.environ.get('BITHUMAN_MODEL_DIR')
    if d:
        пути = []
        for шаблон in ('*.imx', '*.lebundle'):
            пути += glob.glob(os.path.join(d, шаблон))
        for p in sorted(пути):
            out[os.path.splitext(os.path.basename(p))[0]] = p
    one = os.environ.get('BITHUMAN_MODEL_PATH')
    if one and not out:
        out[os.path.splitext(os.path.basename(one))[0]] = one
    return out


