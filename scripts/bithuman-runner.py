                #  этого после загрузки окно учителя оставалось чёрным до первой фразы, и урок
                #  выглядел как «звук есть, картинки нет». Поэтому заводим движок коротким
                #  импульсом тишины ПРЯМО СЕЙЧАС, на экране загрузки: он отрисует кадр, мы его
                #  запомним как заставку, и к первой фразе окно уже живое.
                #  ⚠️ Импульс безопасен именно здесь: он далеко (секунды) от настоящей речи.
                #  Толкать тишину ПЕРЕД самой фразой нельзя — проверено, ломает артикуляцию.
