async def stream(request):
    """MJPEG: гоним свежий кадр из latest ~25 fps. Много клиентов = каждый читает latest."""
    aid = request.query.get('avatar')
    if aid:
        try:
            await use_avatar(aid)
        except Exception as e:
            return web.json_response({'error': str(e)}, status=503, headers=CORS)
    resp = web.StreamResponse(status=200, headers={
        'Content-Type': 'multipart/x-mixed-replace; boundary=frame',
        'Cache-Control': 'no-store, no-cache',
        **CORS,
    })
    await resp.prepare(request)
    # 🔴 18.08. Запись в мёртвый сокет УСПЕВАЕТ (уходит в буфер ядра), а `transport.is_closing()`
    #  остаётся False — поэтому убитый клиент висел «зрителем» бесконечно, и правило
    #  «нет зрителей — нет кадров» не срабатывало. Проверено опытом: клиент убит, зрителей 3.
    #  Лечится на уровне ОС: включаем TCP-keepalive с коротким сроком — ядро само
    #  простучит соединение и оборвёт мёртвое примерно за 11 секунд.
    try:
        сокет = request.transport.get_extra_info('socket')
        if сокет is not None:
            import socket as _s
            сокет.setsockopt(_s.SOL_SOCKET, _s.SO_KEEPALIVE, 1)
            for имя, знач in (('TCP_KEEPIDLE', 5), ('TCP_KEEPINTVL', 3), ('TCP_KEEPCNT', 2)):
                if hasattr(_s, имя):
                    сокет.setsockopt(_s.IPPROTO_TCP, getattr(_s, имя), знач)
    except Exception as e:                                    # noqa: BLE001
        print('keepalive сокета не включился:', e)
    global зрителей, стоп_таймер
    зрителей += 1
    # ⚠️ Здесь СПЕЦИАЛЬНО нет запуска кадров: «просто зашёл» не должно стоить ничего.
    # Зритель увидит последний снятый кадр, а живые кадры включит первая же реплика.
    # 🔴 17.08. Раньше кадр уходил каждые 40 мс ВСЕГДА — в том числе когда он не менялся.
    #  Пока лицо молчит, это 25 одинаковых картинок в секунду, по 40–60 КБ каждая: канал
    #  забит дублями, и речевые кадры доезжают с опозданием, которое РАСТЁТ по ходу фразы.
    #  Замер: раннер отдавал 24 кадра/с, до клиента доезжало 18 — разница копилась в сети,
    #  и к концу длинной фразы губы уходили от звука больше чем на секунду.
    #  Теперь шлём кадр, только если он ИЗМЕНИЛСЯ, плюс один «я жив» раз в секунду, чтобы
    #  соединение не считалось мёртвым и новому зрителю было что показать сразу.
    прошлый = None
    последний_раз = 0.0
    try:
        while True:
            jpg = latest['jpg']
            # ⚠️ Разрыв не всегда прилетает исключением: aiohttp может проглотить запись
            # в мёртвый сокет, и «зритель» висел бы вечно, а кадры считались бы. Спрашиваем
            # транспорт напрямую — это и есть честный признак ухода.
            if request.transport is None or request.transport.is_closing():
                break
            сейчас = time.monotonic()
            новый = jpg is not None and jpg is not прошлый
            пора = (сейчас - последний_раз) > 1.0            # сердцебиение для молчащего лица
            if jpg is not None and (новый or пора):
                прошлый = jpg
                последний_раз = сейчас
                # ⚠️ Запись в мёртвый или очень медленный сокет может ВИСЕТЬ, и такой зритель
                #  держал бы и счётчик зрителей, и генерацию кадров: именно так на раннере
                #  копились «фантомы» — шесть штук при одной живой вкладке. Срок на запись
                #  превращает зависшего в ушедшего, и деньги перестают капать сами.
                try:
                    await asyncio.wait_for(resp.write(
                    b'--frame\r\nContent-Type: image/jpeg\r\nContent-Length: '
                    + str(len(jpg)).encode() + b'\r\n\r\n' + jpg + b'\r\n'), timeout=5)
                except asyncio.TimeoutError:
                    print('⏹ зритель не читает 5 с — считаю ушедшим')
                    break
            await asyncio.sleep(1 / 50)                      # чаще опрашиваем — реже шлём
    except (asyncio.CancelledError, ConnectionResetError, ConnectionError):
        pass
    finally:
        зрителей -= 1
        # Ушёл последний — недоговорённую реплику дальше считать НЕ за кого. Без этого
        # обрыв посреди длинной фразы оплачивался до её конца (замер: 304 кадра впустую).
        if зрителей <= 0 and подача is not None and not подача.done():
            подача.cancel()
            print('⏹ зрителей нет — обрываю подачу звука на полуслове')
        if зрителей <= 0 and стоп_таймер is None:
            стоп_таймер = asyncio.create_task(гасить_потом())
    return resp


async def push(request):
    """Яндекс-PCM16 (mono 16k) → push_audio кусками → flush. Аватар начинает говорить."""
    # 🔴 19.08. Дорогое лицо больше не поднимается на старте службы (иначе капает 2 кр/мин
    #  в пустоту). Значит первая же реплика должна поднять его сама — иначе урок получит
    #  «runtime not ready» там, где раньше всё работало.
    if runtime is None and models():
        try:
            await use_avatar(next(iter(models())))
        except Exception as e:                                # noqa: BLE001
            return web.json_response({'error': f'лицо не поднялось: {e}'}, status=503,
                                     headers=CORS)
    if runtime is None:
        return web.json_response({'error': 'runtime not ready'}, status=503, headers=CORS)
    data = await request.json()
    pcm = base64.b64decode(data.get('b64', '') or '')
    if not pcm:
        return web.json_response({'error': 'no audio'}, status=400, headers=CORS)
    # 🔴 14.08, Кратов: «губами не шевелит, а в какой-то момент очень быстро ими шевелит,
    #  как будто за 1 сек всё сказала». Причина ровно здесь: весь звук заливался в движок
    #  ОДНИМ ЗАЛПОМ, без пауз. Движок держит 115 кадр/с (замер на нашем сервере), поэтому
    #  пятнадцать секунд речи он прожёвывал за четыре — губы отрабатывали и замирали, а
    #  браузер продолжал играть звук в реальном времени. Рассинхрон рос до десяти секунд.
    #  Лечится не скоростью, а ТЕМПОМ: кусок в 0.2 с звука подаётся раз в 0.2 с, и картинка
    #  идёт нога в ногу со звуком в браузере.
    #  ⚠️ Отвечаем СРАЗУ, не дожидаясь конца подачи: иначе HTTP-запрос висел бы всю реплику,
    #  а урок ждёт ответа, чтобы играть звук — получилась бы тишина на всю её длину.
    global подача
    if подача and not подача.done():
        подача.cancel()                       # новая реплика отменяет недоговорённую старую
    latest['last_audio'] = time.time()
    latest['речь_t0'] = time.monotonic()      # часы реплики: от них считается темп выдачи
    latest['кадр0'] = latest.get('кадров', 0)
    качать('заговорила')                      # ВОТ ЗДЕСЬ начинается расход — и только здесь
    подача = asyncio.create_task(кормить(pcm))
    return web.json_response({'ok': True, 'seconds': round(len(pcm) / 2 / 16000, 2)}, headers=CORS)


async def кормить(pcm):
    """Подать PCM в движок В ТЕМПЕ РЕЧИ: кусок 0.2 с — раз в 0.2 с."""
    # 🔴 14.08, второй заход. Кусок 0.2 с давал ~5 РАЗНЫХ кадров в секунду вместо 25:
    #  движок отрабатывает порцию и до следующей повторяет последний кадр. Со стороны это
    #  «звук идёт, а анимации нет». Кадр аватара = 40 мс звука, поэтому и подаём ровно по
    #  40 мс — тогда картинка идёт сплошняком, а не рывками.
    ДОЛЯ = float(os.environ.get('PUSH_CHUNK', '0.04'))
    step = int(16000 * 2 * ДОЛЯ)              # int16 mono 16k = 2 байта на сэмпл
    n = len(pcm)
    i = 0
    t0 = time.monotonic()
    try:
        while i < n:
            chunk = pcm[i:i + step]
            i += step
            await runtime.push_audio(chunk, 16000, last_chunk=(i >= n))
            latest['last_audio'] = time.time()   # реплика ещё идёт — не давать хвосту оборвать
            # спим не «сколько-то», а до момента, когда этот кусок должен был прозвучать:
            # так подача не уползает от звука на длинной реплике
            отставание = (i / 2 / 16000) - (time.monotonic() - t0)
            if отставание > 0:
                await asyncio.sleep(отставание)
        await runtime.flush()
    except asyncio.CancelledError:
        raise
    except Exception as e:                    # noqa: BLE001
        print('подача звука оборвалась:', e)


async def keepalive(request):
    """Держать генератор кадров живым БЕЗ подачи звука. Это и есть честный прогрев.

    🔴 17.08. Сначала грели тишиной через /push — и это оказалось ядом: каждый push
    отменяет недоговорённую подачу (`подача.cancel()`) и закрывает реплику
    (`last_chunk=True` + `flush()`), поэтому идущая СЛЕДОМ речь переставала открывать рот.
    Замер, три круга против трёх: без прогрева размах рта 12.85 · 13.53 · 7.94, с прогревом
    тишиной — 1.01 · 12.85 · 0.00 (дважды рот не открылся вовсе, голова при этом «дышала»).

    Зачем вообще греть: генератор поднимается 2–4 с, а урок ждать не может. Замер: на
    тёплом раннере рот идёт через 0.05–0.35 с, на остывшем — 1.7–4.8 с, и короткая фраза
    целиком укладывается в мёртвое окно.

    ⚠️ Кадры — деньги. Пока сюда стучат, они считаются. Поэтому стучать должен УРОК и
    только пока он идёт: хвост в ХВОСТ секунд гасит генерацию сам, если стук прекратился.
    """
    if runtime is None:
        return web.json_response({'error': 'runtime not ready'}, status=503, headers=CORS)
    # 🔴 18.08, требование Кратова: «чтобы когда я отключусь или закрою — впустую не
    #  тратило». Раньше прогрев ставил `last_audio` и тем самым ОБМАНЫВАЛ оба
    #  предохранителя: и хвост речи, и сторож тишины. Забытая вкладка грелась вечно.
    #  Теперь у прогрева СВОЙ срок, короткий, и три ограничения:
    #   · без зрителей не греем вовсе — смотреть некому;
    #   · греем не дольше ПРОГРЕВ_МАКС секунд от последней НАСТОЯЩЕЙ речи;
    #   · `last_audio` не трогаем — сторож тишины продолжает считать честно.
    if зрителей <= 0:
        return web.json_response({'ok': False, 'почему': 'нет зрителей — греть некого'},
                                 headers=CORS)
    # ⚠️ Считаем не только речь: в НАЧАЛЕ урока речи ещё не было, и жёсткая проверка
    #  «только рядом с речью» отказывала первому же прогреву — кадры не поднимались
    #  вовсе, окно учителя оставалось чёрным. Свежий выбор лица тоже считается.
    с_речи = time.time() - max(latest.get('last_audio', 0), latest.get('выбор', 0))
    if с_речи > ПРОГРЕВ_МАКС:
        return web.json_response({'ok': False, 'почему': f'молчит {int(с_речи)} с — грею только рядом с речью'},
                                 headers=CORS)
    latest['грелка_до'] = time.time() + 2.0
    latest['грелка_была'] = True          # клиент умеет стучать — с него и спросим пульс
    качать('прогрев без звука')
    return web.json_response({'ok': True, 'кадров': latest.get('кадров', 0),
                              'кадры_идут': bool(drain_task and not drain_task.done())},
                             headers=CORS)


