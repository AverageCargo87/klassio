def выключить_счётчик(почему=''):
    """Снять счётчик v2. Модель остаётся в памяти — платить перестаём, лицо не теряем."""
    if not счётчик['вкл']:
        return
    try:
        from bithuman import _essence2light_adapter as v2
        v2.stop_engine_metering()
        счётчик['секунд'] += time.time() - счётчик.get('вкл_в', time.time())
        счётчик['вкл'] = False
        счётчик['снят_в'] = time.time()
        print(f'💤 счётчик v2 СНЯТ — {почему} (наговорили {счётчик["секунд"]:.0f} с '
              f'за {счётчик["циклов"]} включений)')
    except Exception as e:                             # noqa: BLE001
        print('счётчик v2 снять не вышло:', e)


def память_гб():
    """Сколько сейчас занято процессом. На Linux — из /proc, иначе 0."""
    try:
        with open('/proc/self/statm') as ф:
            return int(ф.read().split()[1]) * os.sysconf('SC_PAGE_SIZE') / 1024 ** 3
    except Exception:                                  # noqa: BLE001
        return 0.0
