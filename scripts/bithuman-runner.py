async def сторож_дорогой_модели():
    """🔴 19.08, переписан по замерам. Дорогая модель не должна стоить в паузе НИЧЕГО.

    Прошлая версия (18.08) снимала дорогое лицо, переключаясь на essence-1. Это работало,
    но било по уроку: каждое возвращение — новая загрузка (секунды чёрного окна) и новый
    сеанс с минимальной платой за минуту. Теперь глушим не лицо, а СЧЁТЧИК: модель
    остаётся в памяти, платить перестаём (замер: 4.5 минуты со снятым счётчиком — ноль),
    а к следующей реплике первый кадр приходит через 0.12 с.

    Сторож делает две вещи, обе — по замерам 19.08:
      1) ТИШИНА. Молчит дольше ТИШИНА_СЧЁТЧИКА секунд — счётчик снимаем. Порог маленький
         (12 с): минута простоя v2 стоит 2 кредита, а возврат бесплатный, так что тянуть
         незачем.
      2) ПАМЯТЬ. v2 не отдаёт память: примерно 0.7 ГБ на каждые четыре секунды речи, и
         не освобождает. Замер: одна шестисекундная фраза — 1.65 → 8.84 ГБ, дальше OOM и
         процесс умирает посреди урока. Поэтому в ПАУЗЕ (не посреди фразы!) переродим
         лицо, когда занятое перевалит ПАМЯТЬ_ГБ: перезагрузка стоит секунды, падение по
         OOM стоит урока.
    """
    while True:
        await asyncio.sleep(4)
        if runtime is None or not сейчас_дорогая():
            continue
        тишина = time.time() - max(latest.get('last_audio', 0), latest.get('выбор', 0))
        идут_кадры = bool(drain_task and not drain_task.done())
        if счётчик['вкл'] and тишина > ТИШИНА_СЧЁТЧИКА and not идут_кадры:
            выключить_счётчик(f'молчит {int(тишина)} с')
        # Перерождение по памяти — только в паузе и только со снятым счётчиком.
        занято = память_гб()
        if занято > ПАМЯТЬ_ГБ and not идут_кадры and тишина > ТИШИНА_СЧЁТЧИКА:
            лицо = current['id']
            print(f'🧠 {лицо} занял {занято:.1f} ГБ (потолок {ПАМЯТЬ_ГБ}) — '
                  f'перерождаю лицо, пока пауза')
            try:
                выключить_счётчик('перед перерождением')
                current['id'] = None                    # заставить именно ПЕРЕСОЗДАНИЕ
                await use_avatar(лицо)
                print(f'🧠 после перерождения занято {память_гб():.1f} ГБ')
            except Exception as e:                                # noqa: BLE001
                print('переродить лицо не вышло:', e)


async def main():
    known = models()
    if not SECRET or not known:
        raise SystemExit('нужны BITHUMAN_API_SECRET и BITHUMAN_MODEL_DIR (или BITHUMAN_MODEL_PATH) — см. шапку файла')
    # 🔴 18.08. Раньше здесь падало ВСЁ, если первое лицо по алфавиту не грузится: служба
    #  уходила в цикл перезапуска systemd, а каждая попытка загрузки v2-модели БИЛЛИТСЯ —
    #  в журнале расходов `usage_essence_2_model_self_hosted`, 2 кредита при
    #  `frames_rendered: 0`. За несколько минут цикла так утекло 33 кредита.
    #  Теперь битое лицо пропускаем и живём на следующем, а если не поднялось ни одно —
    #  всё равно поднимаем HTTP, чтобы /health честно сказал причину, а не молчал.
    # 🔴 19.08. Порядок подъёма: сначала ДЕШЁВЫЕ лица. Раньше бралось первое по алфавиту,
    #  и если им оказывалась v2 — служба начинала капать 2 кр/мин с момента старта, ещё до
    #  того, как кто-то открыл урок. Забытая на выходные служба = весь баланс. Дорогое лицо
    #  теперь поднимается только когда его ПОПРОСЯТ (?avatar=… в /health или /stream).
    сломанные = {}
    порядок = sorted(known, key=lambda a: (дорогая(known[a]), a))
    if порядок and дорогая(known[порядок[0]]):
        print('⚠ дешёвых лиц нет — на старте не поднимаю ничего, жду запроса лица')
        порядок = []
    for aid in порядок:
        try:
            await use_avatar(aid)
            break
        except Exception as e:                                  # noqa: BLE001
            сломанные[aid] = str(e)[:200]
            print(f'⚠ лицо «{aid}» не загрузилось, пропускаю: {сломанные[aid]}')
    if runtime is None:
        print('❌ ни одно лицо не загрузилось — поднимаю только HTTP, кадров не будет')
    latest['сломанные'] = сломанные
    # Один кадр на заставку: чтобы в паузе и до первой реплики было что показать.
    # Стоит долю кредита (кадр из полутора тысяч), зато вкладка не встречает чернотой.
    latest['снимок'] = True
    качать('снимок для заставки')

    app = web.Application()
    app.router.add_get('/health', health)
    app.router.add_get('/avatars', avatars)
    app.router.add_get('/stream', stream)
    app.router.add_post('/push', push)
    app.router.add_get('/keepalive', keepalive)
    app.router.add_route('OPTIONS', '/{tail:.*}', preflight)
    asyncio.create_task(сторож_дорогой_модели())    # дорогая модель не живёт в простое
    runner = web.AppRunner(app)
    await runner.setup()
    port = int(os.environ.get('PUSH_PORT', '8090'))
    await web.TCPSite(runner, '0.0.0.0', port).start()
    print(f'✅ bitHuman раннер: http://0.0.0.0:{port}  (/health /avatars /stream /push)')
    print('   лица: ' + ', '.join(known) if known else '   лиц нет')
    await asyncio.Event().wait()  # держим процесс


if __name__ == '__main__':
    asyncio.run(main())
