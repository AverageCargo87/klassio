def движок(путь):
    """Какой движок у модели: 'essence1', 'essence2-light', … Читаем МАНИФЕСТ, не имя.

    ⚠️ По имени файла определять нельзя: скачанный из кабинета essence-2 называется
    `A59FCC1810.lebundle.imx` — прежняя проверка `endswith('.lebundle')` на нём молчала,
    и дорогая модель считалась дешёвой. Манифест не соврёт.
    """
    try:                                               # у SDK 2.9 есть готовый определитель
        from bithuman._imx_engine import engine_id_for_path
        e = engine_id_for_path(путь)
        if e:
            return e
    except Exception:                                  # noqa: BLE001
        pass
    try:
        if os.path.isdir(путь):
            with open(os.path.join(путь, 'manifest.json'), encoding='utf-8') as ф:
                return json.load(ф).get('engine') or 'essence1'
    except Exception:                                  # noqa: BLE001
        pass
    return 'essence2-light' if путь.endswith('.lebundle') else 'essence1'


def дорогая(путь):
    """v2-семейство: платит по времени жизни сеанса, а не за кадры."""
    return движок(путь) in V2_ДВИЖКИ


