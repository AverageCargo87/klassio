#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════════════════
//  ПРОВЕРКА ГОЛОСА НА САМЫХ ОПАСНЫХ ТАКТАХ УРОКА
//
//  Слушать 73 такта руками невозможно, а «синтез ответил 200» ничего не доказывает:
//  Яндекс возвращает 200 и когда читает «ПОДВЕДЁМ ИТОГИ» по буквам. Поэтому меряем
//  ДЛИТЕЛЬНОСТЬ и сверяем её с длиной текста: нормальная речь идёт 13–17 знаков в
//  секунду, а если движок начал диктовать по буквам или спотыкаться на числах —
//  длительность уезжает в разы, и это видно числом.
//
//  Берём не подряд, а ОПАСНЫЕ места: там, где в тексте числа, века, «нашей эры»,
//  заглавные заголовки, греческие имена и наши собственные ярлыки.
//
//  node scripts/progon-golosa.mjs [--все]     # --все: прогнать весь урок (платно!)
//  Ролики кладутся в .tmp/golos-progon/ — можно послушать руками.
// ═══════════════════════════════════════════════════════════════════════════
import fs from 'node:fs'
import { execFileSync } from 'node:child_process'

const URL = process.env.KNIGA_URL || 'http://localhost:8781'
const ВСЕ = process.argv.includes('--все')
const OUT = '.tmp/golos-progon'
fs.mkdirSync(OUT, { recursive: true })

const скрипт = JSON.parse(fs.readFileSync('.tmp/_script.json', 'utf8')).такты

// ── что берём на прослушку ─────────────────────────────────────────────────
// Каждый пункт — не «случайный такт», а конкретный риск.
const РИСКИ = [
  { имя: 'числа-века', re: /\d+-го тысячелетия|\d+ века до нашей эры/, зачем: 'римские цифры заменены арабскими — не читает ли «до нашей эры» как «до н э»' },
  { имя: 'заголовок-капсом', re: /^[А-ЯЁ\s]{8,}$/, зачем: 'заголовок капсом может уехать в чтение по буквам' },
  { имя: 'наш-ярлык', re: /^(Новые слова|Новое имя|Параграф \d)/, зачем: 'ярлыки, которые добавляем мы сами' },
  { имя: 'висячий-дефис', re: /трёх- и/, зачем: 'место, где раньше склеивалось в «трёхи»' },
  { имя: 'греческие-имена', re: /Пелопоннес|Фессалия|эллины|Кноссе|ахейцев/, зачем: 'имена без знаков ударения — не ломается ли произношение' },
  { имя: 'нумерованный-вопрос', re: /^\d\.\s.+\?\s*\d\./, зачем: 'два вопроса в одном такте, номера внутри' },
  { имя: 'кавычки-цитата', re: /«[^»]{20,}»/, зачем: 'длинная цитата в кавычках' },
]
const выбор = []
if (ВСЕ) выбор.push(...скрипт.map((b) => ({ b, риск: 'весь урок' })))
else for (const р of РИСКИ) {
  const b = скрипт.find((x) => р.re.test(x.say || ''))
  if (b && !выбор.some((v) => v.b.n === b.n)) выбор.push({ b, риск: р.имя, зачем: р.зачем })
  else if (!b) console.log('⚠ не нашёл такта под риск «' + р.имя + '»')
}
// плюс первый и последний — начало и конец урока слышит каждый
for (const n of [1, скрипт.length]) if (!выбор.some((v) => v.b.n === n)) выбор.push({ b: скрипт[n - 1], риск: n === 1 ? 'первая фраза' : 'последняя фраза' })

console.log('на прослушку: ' + выбор.length + ' тактов\n')

const длительность = (файл) => {
  const t = execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', файл], { encoding: 'utf8' })
  return Number(String(t).trim())
}

let бед = 0, знаковВсего = 0, секундВсего = 0
for (const { b, риск, зачем } of выбор) {
  const тело = { voice: 'alena', role: 'good', speed: 0.95, text: b.say }
  // ⚠️ Квота синтеза у Яндекса узкая, а стенд один на всех: без паузы и повтора
  //  прогон падает на ECONNRESET и выглядит как поломка голоса, хотя голос жив.
  const t0 = Date.now()
  let r = null, срыв = ''
  for (let п = 0; п < 3 && !r; п++) {
    if (п) await new Promise((res) => setTimeout(res, 1500 * п))
    try { r = await fetch(URL + '/api/tts', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(тело) }) }
    catch (e) { срыв = e.message + (e.cause ? ' / ' + e.cause.code : '') }
  }
  const мс = Date.now() - t0
  if (!r) { бед++; console.log('❌ такт ' + b.n + ' (' + риск + '): связь оборвалась трижды — ' + срыв); continue }
  if (!r.ok) { бед++; console.log('❌ такт ' + b.n + ' (' + риск + '): синтез ответил ' + r.status + ' ' + (await r.text()).slice(0, 120)); continue }
  const buf = Buffer.from(await r.arrayBuffer())
  const файл = OUT + '/takt-' + String(b.n).padStart(2, '0') + '-' + риск + '.mp3'
  fs.writeFileSync(файл, buf)
  let сек = 0
  try { сек = длительность(файл) } catch { /* ffprobe не нашёлся */ }
  const знаков = b.say.length
  знаковВсего += знаков; секундВсего += сек
  const темп = сек ? (знаков / сек) : 0
  // Живая русская речь — 13–17 знаков в секунду. Ниже 8 = что-то диктуется по буквам
  // или движок вставляет паузы там, где их быть не должно; выше 24 = проглатывает.
  const плохо = сек && (темп < 8 || темп > 24)
  if (плохо) бед++
  console.log((плохо ? '❌' : '✅') + ' такт ' + String(b.n).padStart(2) + ' · ' + риск.padEnd(20)
    + знаков + ' знаков · ' + сек.toFixed(1) + ' с · ' + темп.toFixed(1) + ' зн/с · синтез ' + мс + ' мс')
  if (зачем && плохо) console.log('     риск: ' + зачем)
  await new Promise((res) => setTimeout(res, 900))   // не упираемся в квоту синтеза
  console.log('     «' + b.say.slice(0, 96) + (b.say.length > 96 ? '…' : '') + '»')
}

// ── СЛУХОВАЯ СВЕРКА ────────────────────────────────────────────────────────
//  Длительность ловит «читает по буквам», но не ловит «прочитало НЕ ТО»: «3-м» может
//  выйти «третьим эм», «20 века» — «двадцать века». Проверить это на глаз нельзя, а на
//  слух — можно: гоним синтез ОБРАТНО через распознавание Яндекса и печатаем, что оно
//  услышало. Совпадение слово в слово тут не нужно и невозможно (числа STT пишет
//  словами) — нужно ГЛАЗАМИ увидеть, не появилось ли «эм», «н э», «трёхи».
const ОПАСНЫЕ = [
  'ПОДВЕДЁМ ИТОГИ',
  'Параграф 20. Начало греческой цивилизации',
  'Новые слова: мегарон, фреска',
  'Новое имя: Минос',
  'Некоторые части дворца были трёх- и даже четырёхэтажные.',
  'Именно здесь в 3-м — середине 2-го тысячелетия до нашей эры существовала первая европейская цивилизация.',
  'Она окончательно прекратила своё существование в середине 15 века до нашей эры.',
  'Позднее все древние греки называли себя одним общим именем — эллины, а свою родину — Элладой.',
]
console.log('')
console.log('── что слышит распознавание (синтез → Яндекс STT → текст) ──')
const слышно = []
for (const фраза of ОПАСНЫЕ) {
  await new Promise((r) => setTimeout(r, 900))
  let rr = null
  try { rr = await fetch(URL + '/api/tts', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ voice: 'alena', role: 'good', speed: 0.95, text: фраза }) }) } catch {}
  if (!rr || !rr.ok) { console.log('  не синтезировалось: ' + фраза.slice(0, 40)); continue }
  const mp3 = OUT + '/sluh.mp3', pcm = OUT + '/sluh.pcm'
  fs.writeFileSync(mp3, Buffer.from(await rr.arrayBuffer()))
  // STT принимает сырой LPCM 16 кГц моно — перегоняем ffmpeg
  execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', mp3, '-f', 's16le', '-ar', '16000', '-ac', '1', pcm])
  await new Promise((res) => setTimeout(res, 900))
  let j = {}
  try {
    const q = await fetch(URL + '/api/stt', { method: 'POST', headers: { 'Content-Type': 'application/octet-stream' }, body: fs.readFileSync(pcm) })
    j = await q.json()
  } catch (e) { j = { error: e.message } }
  console.log('  сказали : ' + фраза)
  console.log('  услышали: ' + (j.text || ('— ' + (j.error || 'пусто'))))
  слышно.push({ фраза, услышано: j.text || '', ошибка: j.error || null })
}
fs.writeFileSync(OUT + '/sluh.json', JSON.stringify(слышно, null, 1))
try { fs.unlinkSync(OUT + '/sluh.pcm'); fs.unlinkSync(OUT + '/sluh.mp3') } catch {}

console.log('\nвсего ' + знаковВсего + ' знаков → ' + секундВсего.toFixed(1) + ' с речи'
  + (секундВсего ? ' (' + (знаковВсего / секундВсего).toFixed(1) + ' знаков в секунду в среднем)' : ''))
console.log('ролики → ' + OUT + ' — можно послушать руками')
console.log(бед ? ('\n❌ подозрительных тактов: ' + бед) : '\n✅ голос ровный на всех опасных местах')
process.exit(бед ? 1 : 0)
