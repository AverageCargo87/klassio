const ABBR = /(^|\s)(н\.\s?э|до н\.\s?э|т\.\s?д|т\.\s?п|см|рис|стр|[А-ЯЁ])\.\s*$/
// то же деление на предложения, что в уроке: сокращения концом фразы не считаем
function sentences(t) {
  const parts = String(t || '').split(/(?<=[.!?…»])\s+/), out = []
  let cur = ''
  for (const part of parts) {
    cur = cur ? cur + ' ' + part : part
    if (ABBR.test(cur)) continue
    out.push(cur); cur = ''
  }
  if (cur.trim()) out.push(cur.trim())
  return out
}
const re = (s) => { try { return new RegExp(s, 'i') } catch (e) { return null } }
const beatOf = (r) => SCRIPT.find((b) => r && r.test(b.say || ''))
// предложение учебника, в котором факт и сказан
function srcLine(r) {
  const b = beatOf(r); if (!b) return null
  const s = sentences(b.say).find((x) => r.test(x))
  return { beat: b.n, page: b.page, text: (s || b.say).trim() }
}
// Картинка к термину: показ, привязанный к ТОМУ ЖЕ такту. Из нескольких выбираем не
// просто ближайший по тексту, а тот, чья подпись перекликается с самим термином:
// у «Трёх частей Греции» ближайшим оказывался показ «СЕВЕРНАЯ ГРЕЦИЯ», хотя термин
// про все три части сразу и правильная картинка — общая карта.
const words = (s) => String(s || '').toLowerCase().replace(/ё/g, 'е')
  .split(/[^а-яa-z0-9]+/).filter((w) => w.length > 3)
function artFor(r, pageDemos, term, txt) {
  const b = beatOf(r); if (!b) return null
  const at = r.exec(b.say).index
  const mine = new Set(words(term + ' ' + txt))
  let best = null, bestScore = -1e9
  const hit = []
  for (const d of pageDemos) {
    const dr = re(d.re); if (!dr) continue
    const m = dr.exec(b.say || ''); if (!m) continue
    const common = words(d.cap + ' ' + d.sub).filter((w) => mine.has(w)).length
    if (common) hit.push(d)
    // общие слова весят больше близости: близость лишь разводит равных
    const score = common * 100 - Math.abs(m.index - at) / 10
    if (score > bestScore) { bestScore = score; best = d }
  }
  // Термин, который перекликается сразу с НЕСКОЛЬКИМИ местами на карте, — это термин
  // про общий вид: «Три части Греции» бьётся и в Северную, и в Среднюю, и в Южную,
  // и правильная картинка тут — вся Греция целиком, а не одна из третей.
  if (hit.length >= 2 && hit.every((d) => d.art.startsWith('map'))) {
    const whole = pageDemos.find((d) => d.art === 'map')
    if (whole) return { art: 'map', cap: whole.cap, sub: whole.sub }
    return { art: 'map', cap: best.cap, sub: best.sub }
  }
  return best ? { art: best.art, cap: best.cap, sub: best.sub } : null
}

