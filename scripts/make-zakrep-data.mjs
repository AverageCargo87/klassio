const pages = []
for (const pg of PANEL) {
  const terms = []
  for (const t of pg.teasers || []) {
    const r = re(t.re); if (!r) continue
    const src = srcLine(r)
    const vis = BY_HAND[t.term] || artFor(r, pg.demos || [], t.term, t.txt)
    terms.push({ term: t.term, txt: t.txt, art: vis && vis.art, cap: vis && vis.cap,
      src: src && src.text, sum: САМАРИ[t.term], beat: src && src.beat })
  }
  const qs = ((TEST.find((x) => x.page === pg.page) || {}).questions || []).map((q) => {
    const r = re(q.re), src = r && srcLine(r)
    return { q: q.q, options: q.options, ok: q.ok, term: q.term,
      src: src && src.text, beat: src && src.beat,
      // чем закрыть «покажем варианты с неправильными ответами и объясним»:
      // готового текста нет, помечаем место, где он должен появиться
      why: q.options.map((o, i) => i === q.ok ? null : null) }
  })
  pages.push({ page: pg.page, terms, questions: qs })
}

