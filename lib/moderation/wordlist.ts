// Russian profanity / rudeness lexicon for behaviour moderation.
//
// PRECISION-FIRST (heuristic v1). Patterns are anchored to a WHOLE token
// (^...$) with inflectional suffixes, NOT loose substring matches — so an
// astronomy lesson's «небо», «корабля», «спутник», «сухой» can never false-
// trigger. Recall gaps are intentionally covered by the agent's own prompt
// (LESSON-FLOW.md §7 — two layers: server filter + agent behaviour).
//
// All patterns assume input has passed through normalize() (lowercase,
// ё→е, look-alikes folded, runs collapsed). Hence only «е» (never «ё»).

/** Obscenities (мат) → severity 'profanity'. */
export const PROFANITY_PATTERNS: RegExp[] = [
  // хуй и производные (не трогает «худой», «хутор», «хук»)
  /^(?:по|на|до|о|ни|пере)?ху(?:й|и|ю|я|е|ем|ев|йл[а-я]*|йн[а-я]*|яр[а-я]*)$/,
  /^о?хуе[а-я]*$/, // охуеть, хуево, хуесос, охуенно
  // пизд-
  /^(?:с|на|вы|по|о|за)?пизд[а-я]*$/,
  /^пизж[а-я]*$/,
  // еб-: требует глагольных окончаний/дериватов → «небо», «хлеб», «себя»,
  // «требовать» не совпадают (anchored, нет голого суффикса «о/я/е»)
  /^(?:вы|за|на|по|до|у|от|подо?|разъ?|съ?|изъ?|объ?|пере|недо)?[еэ]б(?:а(?:ть|л[а-я]*|н[а-я]*|ю|ешь|ет[а-я]*|ем[а-я]*|ете|ут)|ну[а-я]*|ёт|ешь|ись|ис[а-я]*|ло|ла|ли|ан[а-я]*|ач[а-я]*|ор[а-я]*|ок[а-я]*|ло[а-я]*|лан[а-я]*|ал[а-я]*)$/,
  /^уеб[а-я]*$/, // уебок, уebать-производные
  // бляд / блят (не трогает «блин», «корабля» — anchored ^бл)
  /^бля(?:дь?|д[а-я]*|т[ьи]?|т[а-я]*|ь)?$/,
  /^бл[яи]{1,}$/, // бля, бляя, бли
  // сук- (не трогает «сукно», «суккуб», «сухой»)
  /^сук(?:а|и|у|е|ой|ам[а-я]*|ин[а-я]*|а[мн][а-я]*)?$/,
  /^сучк[а-я]*$/, // сучка/сучке (не «сучок» — нет окончания «ок»)
  // прочее ядро
  /^муда[кч][а-я]*$/, // мудак (не «мудрый»)
  /^долб[оа]еб[а-я]*$/,
  /^пид[оае]р[а-я]*$/, // пидор/пидар (не «период», «пирамида»)
  /^педик[а-я]*$/,
  /^г[ао]ндон[а-я]*$/,
  /^залуп[а-я]*$/,
  /^манда[а-я]*$/, // манда/мандавошка (не «команда» — anchored)
  /^мраз[ьи][а-я]*$/,
  /^гнид[аыоуе][а-я]*$/,
]

